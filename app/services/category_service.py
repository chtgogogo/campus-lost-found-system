"""类目家族服务（v12 新增）：自定义类目的「家族归属 + 歧义桥」匹配。

## 解决的问题（PRD-v12 §1）

YOLO 系统类目只有 11 类 + 「其他」。用户自定义填写的类目（银行卡 / 学生证 /
充电宝 / 遮阳伞…）此前只有两条路：文字完全相等（20 分）或互不相干（0 分），
导致「失主写银行卡、拾主写学生证」这类**同族不同词**的组合在召回与打分两端都漏。

## 设计（三级匹配，刻意不用向量化语义模型）

- 家族表 `CATEGORY_FAMILIES`：把常见校园物品归入 11 个家族（证件卡类 / 数码电子 /
  钥匙类…）。同家族 = 「大概率是同一种东西的邻近说法」→ 打分给 15 分档、召回放行。
- 歧义桥 `AMBIGUOUS_BRIDGES`：seed 内真实存在的歧义词对（「笔记本」= 本子 vs
  「笔记本电脑」= 电脑），允许特定**跨家族**对按同家族处理，避免 YOLO 识别与
  用户手填永远错开。
- 刻意不做 CLIP/向量语义相似度：中文短词的向量相似度阈值不稳定，且推理成本高；
  家族表是词典方案，O(1) 查表、跨环境确定性（与 v10 黄金用例的可复现原则一致）。

## 与既有代码的关系

- 打分接入：`match_service._score_photo_category` 在「精确(20)」之后、「子串近似(10)」
  之前插入「同家族(15)」档；档位常量 `PHOTO_CAT_FAMILY` 在 `scoring_refs.py`（单一事实源）。
- 召回接入：`publish_service._recall_*_candidates` 的 `_recalled` 增加「同家族也召回」。
"""

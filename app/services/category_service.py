# 歧义桥：跨家族但实际常指同一物的词对（frozenset 便于无序比较）
AMBIGUOUS_BRIDGES: frozenset[frozenset[str]] = frozenset(
    {
        frozenset({"笔记本", "笔记本电脑"}),  # 本子 vs 电脑：YOLO 识别 laptop、用户常写「笔记本」
    }
)

# 词 → 家族名 的倒排索引（O(1) 查表）
_WORD_TO_FAMILY: dict[str, str] = {
    word: family for family, words in CATEGORY_FAMILIES.items() for word in words
}


def family_of(name: str | None) -> str | None:
    """查词所属家族；未收录 / 空 / 「其他」返回 None（不参与家族匹配）。

    Args:
        name: 类目名（原文，不去空格外不做归一——家族表收词即为标准形态）。

    Returns:
        家族名或 None。永不抛异常。
    """
    if not name:
        return None
    return _WORD_TO_FAMILY.get(str(name).strip())


def same_family(name1: str | None, name2: str | None) -> bool:
    """判断两个类目是否同家族（含歧义桥）。

    任一词未收录、为空或相等（相等走精确档，无需家族）→ False。
    """
    w1 = (name1 or "").strip()
    w2 = (name2 or "").strip()
    if not w1 or not w2 or w1 == w2:
        return False
    f1, f2 = _WORD_TO_FAMILY.get(w1), _WORD_TO_FAMILY.get(w2)
    if f1 is not None and f1 == f2:
        return True
    return frozenset({w1, w2}) in AMBIGUOUS_BRIDGES


def category_affinity(name1: str | None, name2: str | None) -> float:
    """类目亲和度（供解释/调试用；打分主路径用 same_family + 档位常量）。

    Returns:
        1.0 文字相等 / 0.75 同家族或歧义桥 / 0.0 无关系。
    """
    w1 = (name1 or "").strip()
    w2 = (name2 or "").strip()
    if w1 and w1 == w2:
        return 1.0
    return 0.75 if same_family(w1, w2) else 0.0

"""校园物品同义词词典（v18：Query Rewrite 的本地知识库层）。

三层结构（单一事实源，match_service 打分与 tag 流水线统一引用）：

1. ``_GROUPS``：**等价组**——组内词两两互为同义（token 级完全相等时互认）。
   含 v18 之前 match_service._ZH_SYNONYMS 的全部存量组（数据原样迁移，行为不变），
   以及校园常见物品的形态/叫法组（坨坨伞=折叠伞、饭卡=校园卡、充电砖=充电宝…）。
2. ``SLANG_TO_STANDARD``：**俚语探测层**——特异性俚语 → 组内任一标准词。
   用于「子串探测」：用户整句无标点（"像枪一样的短收缩伞"被分词成正则切成的一整块
   token）时，token 内**包含**俚语子串即把标准词注入词集，解决长 token 对不上词表的问题。
   只收特异性强的俚语——通用词（手机/伞/电脑）**严禁**入此层，否则"手机壳"会误命中"手机"。
3. ``synonym_lookup(token)`` / ``expand_slang(tokens)``：给 match_service 的两个查询口。

设计约束：
- 本地知识库，**无条件生效**（不依赖 nltk / USE_WORDNET 开关）——离线服务器同样享受同义命中。
- 组内互等是"失物招领粗粒度对等"（坨坨伞≈折叠伞、储蓄卡≈银行卡），不是词典学严格同义；
  每组至少 2 个成员；拿不准的写法宁可不收（误等价会抬高误配率，被评测门禁拦下）。
"""
from __future__ import annotations

